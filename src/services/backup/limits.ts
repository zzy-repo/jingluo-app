/**
 * 备份自己的**容量上限**（#1005）：只有常量，没有逻辑。
 *
 * 为什么单独一个文件，而不是塞进 `services/limits.ts` 的总表：那张表是**运行期可调阈值**
 * （超时 / 预算 / 体积分档），调错了只是体验差一点；而这里这个数字是**数据保留契约**的一部分 ——
 * 改它等于改「用户的数据最多会被删到第几份」。它必须和 `backupCore.ts` 的保留策略一起读，
 * 所以放在同一个目录下，并且**全仓只有这一处**写死（不要在 api / 视图里再出现第二个 2）。
 */

/**
 * **安全备份**（每次恢复前为「当前数据」自动写下的那份）保留几份。
 *
 * 为什么是 2：
 *  - 留 1 太狠 —— 一次恢复可能产出一份**可疑**的安全备份（写入期间盘已经紧张、内容语义不完整，
 *    但字节层面过得去校验）。只有 1 份时，用户再恢复一次就把「恢复之前的样子」彻底覆盖掉了，
 *    而那正是他最想回去的地方；
 *  - 留 2 刚好兜住「上一份也好不到哪去」：一份是此刻的数据，一份是上一次恢复前的数据；
 *  - 再多没有意义 —— 两份以上的历史安全备份与常规备份内容高度冗余，却各自占着整个库的体积
 *    （设备实测单份 43MB，两次恢复就把目录从 3 份涨到 5 份 / 约 226MB）。
 *
 * 另：安全备份**不占**常规备份的名额（`backupCore.selectPrunable` 只数常规备份），
 * 所以「备份目录最多几份」= `RETENTION_KEEP`（常规）+ 本常量（安全），是个**有上界的数**。
 */
export const SAFETY_RETENTION_KEEP = 2
